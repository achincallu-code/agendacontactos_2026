"""Acceso a contactos en SQLite local o PostgreSQL configurado por entorno."""
import os
import sqlite3
from pathlib import Path

RUTA_DB = Path(__file__).with_name("contactos.db")
DATABASE_URL = os.environ.get("DATABASE_URL")


def conectar():
    """Abre una conexión SQLite local o PostgreSQL si hay DATABASE_URL."""
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(
            DATABASE_URL,
            connect_timeout=10,
            row_factory=dict_row,
            sslmode="require",
        )

    conexion = sqlite3.connect(RUTA_DB)
    conexion.row_factory = sqlite3.Row
    return conexion


def _ejecutar(consulta, parametros=(), modo=None):
    """Ejecuta una consulta con los marcadores de parámetros del motor actual."""
    if DATABASE_URL:
        consulta = consulta.replace("?", "%s")

    conexion = conectar()
    try:
        cursor = conexion.cursor()
        try:
            cursor.execute(consulta, parametros)
            if modo == "uno":
                return cursor.fetchone()
            if modo == "todos":
                return cursor.fetchall()
            conexion.commit()
        finally:
            cursor.close()
    finally:
        conexion.close()


def crear_tabla():
    """Crea la tabla contactos si todavía no existe."""
    if DATABASE_URL:
        _ejecutar("""
            CREATE TABLE IF NOT EXISTS contactos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre TEXT NOT NULL,
                telefono TEXT NOT NULL,
                correo TEXT,
                categoria TEXT NOT NULL
            )
        """)
        return

    _ejecutar("""
        CREATE TABLE IF NOT EXISTS contactos (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nombre TEXT NOT NULL,
            telefono TEXT NOT NULL,
            correo TEXT,
            categoria TEXT NOT NULL
        )
    """)


def obtener_contactos():
    """READ: devuelve todos los contactos ordenados por nombre."""
    return _ejecutar(
        "SELECT * FROM contactos ORDER BY LOWER(nombre)",
        modo="todos",
    )


def obtener_contacto(contacto_id):
    """Busca un contacto específico por su ID."""
    return _ejecutar(
        "SELECT * FROM contactos WHERE id = ?",
        (contacto_id,),
        modo="uno",
    )


def agregar_contacto(nombre, telefono, correo, categoria):
    """CREATE: inserta un registro nuevo usando parámetros SQL."""
    _ejecutar(
        """INSERT INTO contactos (nombre, telefono, correo, categoria)
           VALUES (?, ?, ?, ?)""",
        (nombre, telefono, correo, categoria),
    )


def actualizar_contacto(contacto_id, nombre, telefono, correo, categoria):
    """UPDATE: modifica los datos del contacto cuyo ID coincide."""
    _ejecutar(
        """UPDATE contactos
           SET nombre = ?, telefono = ?, correo = ?, categoria = ?
           WHERE id = ?""",
        (nombre, telefono, correo, categoria, contacto_id),
    )


def eliminar_contacto(contacto_id):
    """DELETE: elimina el registro cuyo ID coincide."""
    _ejecutar(
        "DELETE FROM contactos WHERE id = ?",
        (contacto_id,),
    )


def verificar_conexion():
    """Comprueba que se puede consultar la base de datos configurada."""
    return _ejecutar("SELECT 1 AS estado", modo="uno")
