"""Acceso a cuentas y contactos en SQLite local o PostgreSQL."""
import os
import sqlite3
from pathlib import Path

RUTA_DB = Path(__file__).with_name("contactos.db")
DATABASE_URL = os.environ.get("DATABASE_URL")


def conectar():
    """Abre una conexión SQLite local o PostgreSQL si hay DATABASE_URL."""
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(
            DATABASE_URL,
            connect_timeout=10,
            row_factory=dict_row,
            sslmode="require",
        )

    conexion = sqlite3.connect(RUTA_DB)
    conexion.row_factory = sqlite3.Row
    conexion.execute("PRAGMA foreign_keys = ON")
    return conexion


def _ejecutar(consulta, parametros=(), modo=None):
    """Ejecuta una consulta con los marcadores de parámetros del motor actual."""
    if DATABASE_URL:
        consulta = consulta.replace("?", "%s")

    conexion = conectar()
    try:
        cursor = conexion.cursor()
        try:
            cursor.execute(consulta, parametros)
            if modo == "uno":
                resultado = cursor.fetchone()
            elif modo == "todos":
                resultado = cursor.fetchall()
            elif modo == "rowcount":
                resultado = cursor.rowcount
            else:
                resultado = None
            conexion.commit()
            return resultado
        finally:
            cursor.close()
    finally:
        conexion.close()


def crear_tabla():
    """Crea las tablas y agrega la columna de propietario a bases existentes."""
    if DATABASE_URL:
        _ejecutar("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(80) NOT NULL,
                correo VARCHAR(254) NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        _ejecutar("""
            CREATE TABLE IF NOT EXISTS contactos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre TEXT NOT NULL,
                telefono TEXT NOT NULL,
                correo TEXT,
                categoria TEXT NOT NULL,
                usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE
            )
        """)
        _ejecutar("""
            ALTER TABLE contactos
            ADD COLUMN IF NOT EXISTS usuario_id BIGINT
            REFERENCES usuarios(id) ON DELETE CASCADE
        """)
        return

    _ejecutar("""
        CREATE TABLE IF NOT EXISTS usuarios (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nombre TEXT NOT NULL,
            correo TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            creado_en TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    _ejecutar("""
        CREATE TABLE IF NOT EXISTS contactos (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            nombre TEXT NOT NULL,
            telefono TEXT NOT NULL,
            correo TEXT,
            categoria TEXT NOT NULL,
            usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE
        )
    """)
    columnas = _ejecutar("PRAGMA table_info(contactos)", modo="todos")
    if not any(columna["name"] == "usuario_id" for columna in columnas):
        _ejecutar("""
            ALTER TABLE contactos
            ADD COLUMN usuario_id INTEGER REFERENCES usuarios(id) ON DELETE CASCADE
        """)


def obtener_usuario_por_correo(correo):
    """Busca una cuenta por su correo normalizado."""
    return _ejecutar(
        "SELECT id, nombre, correo, password_hash FROM usuarios WHERE correo = ?",
        (correo,),
        modo="uno",
    )


def obtener_usuario(usuario_id):
    """Busca los datos públicos de una cuenta por su identificador."""
    return _ejecutar(
        "SELECT id, nombre, correo FROM usuarios WHERE id = ?",
        (usuario_id,),
        modo="uno",
    )


def crear_usuario(nombre, correo, password_hash):
    """Crea una cuenta y devuelve su identificador."""
    if DATABASE_URL:
        usuario = _ejecutar(
            """INSERT INTO usuarios (nombre, correo, password_hash)
               VALUES (?, ?, ?) RETURNING id""",
            (nombre, correo, password_hash),
            modo="uno",
        )
        return usuario["id"]

    conexion = conectar()
    try:
        cursor = conexion.execute(
            """INSERT INTO usuarios (nombre, correo, password_hash)
               VALUES (?, ?, ?)""",
            (nombre, correo, password_hash),
        )
        usuario_id = cursor.lastrowid
        conexion.commit()
        return usuario_id
    finally:
        conexion.close()


def asignar_contactos_sin_dueno(usuario_id):
    """Asigna los contactos antiguos sin propietario a una cuenta verificada."""
    _ejecutar(
        "UPDATE contactos SET usuario_id = ? WHERE usuario_id IS NULL",
        (usuario_id,),
    )


def obtener_contactos(usuario_id):
    """READ: devuelve únicamente los contactos de la cuenta indicada."""
    return _ejecutar(
        """SELECT * FROM contactos
           WHERE usuario_id = ?
           ORDER BY LOWER(nombre)""",
        (usuario_id,),
        modo="todos",
    )


def obtener_contacto(contacto_id, usuario_id):
    """Busca un contacto que pertenezca a la cuenta indicada."""
    return _ejecutar(
        "SELECT * FROM contactos WHERE id = ? AND usuario_id = ?",
        (contacto_id, usuario_id),
        modo="uno",
    )


def agregar_contacto(nombre, telefono, correo, categoria, usuario_id):
    """CREATE: inserta un contacto asociado a su propietario."""
    _ejecutar(
        """INSERT INTO contactos (nombre, telefono, correo, categoria, usuario_id)
           VALUES (?, ?, ?, ?, ?)""",
        (nombre, telefono, correo, categoria, usuario_id),
    )


def actualizar_contacto(contacto_id, nombre, telefono, correo, categoria, usuario_id):
    """UPDATE: modifica solo el contacto cuyo ID y propietario coinciden."""
    filas_actualizadas = _ejecutar(
        """UPDATE contactos
           SET nombre = ?, telefono = ?, correo = ?, categoria = ?
           WHERE id = ? AND usuario_id = ?""",
        (nombre, telefono, correo, categoria, contacto_id, usuario_id),
        modo="rowcount",
    )
    return filas_actualizadas > 0


def eliminar_contacto(contacto_id, usuario_id):
    """DELETE: elimina solo el contacto perteneciente a la cuenta indicada."""
    filas_eliminadas = _ejecutar(
        "DELETE FROM contactos WHERE id = ? AND usuario_id = ?",
        (contacto_id, usuario_id),
        modo="rowcount",
    )
    return filas_eliminadas > 0


def verificar_conexion():
    """Comprueba que se puede consultar la base de datos configurada."""
    return _ejecutar("SELECT 1 AS estado", modo="uno")
