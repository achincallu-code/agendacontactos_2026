"""Copia los contactos locales de SQLite a una base PostgreSQL vacía."""

import os
import sqlite3
from pathlib import Path

import psycopg

RUTA_DB = Path(__file__).with_name("contactos.db")
DATABASE_URL = os.environ.get("DATABASE_URL")


def migrar():
    if not DATABASE_URL:
        raise RuntimeError("Define DATABASE_URL con la conexión de PostgreSQL destino.")
    if not RUTA_DB.exists():
        raise FileNotFoundError(f"No se encontró la base de datos local: {RUTA_DB}")

    sqlite = sqlite3.connect(RUTA_DB)
    sqlite.row_factory = sqlite3.Row
    try:
        contactos = sqlite.execute(
            "SELECT id, nombre, telefono, correo, categoria FROM contactos ORDER BY id"
        ).fetchall()
    finally:
        sqlite.close()

    if not contactos:
        print("La base SQLite no contiene contactos para migrar.")
        return

    with psycopg.connect(
        DATABASE_URL,
        connect_timeout=10,
        sslmode="require",
    ) as postgres:
        with postgres.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS contactos (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre TEXT NOT NULL,
                    telefono TEXT NOT NULL,
                    correo TEXT,
                    categoria TEXT NOT NULL
                )
            """)
            cursor.execute("SELECT COUNT(*) FROM contactos")
            if cursor.fetchone()[0]:
                raise RuntimeError(
                    "La tabla destino ya tiene contactos; no se migró ningún dato."
                )

            cursor.executemany(
                """INSERT INTO contactos (id, nombre, telefono, correo, categoria)
                   VALUES (%s, %s, %s, %s, %s)""",
                [
                    (
                        contacto["id"],
                        contacto["nombre"],
                        contacto["telefono"],
                        contacto["correo"],
                        contacto["categoria"],
                    )
                    for contacto in contactos
                ],
            )
            cursor.execute("""
                SELECT setval(
                    pg_get_serial_sequence('contactos', 'id'),
                    (SELECT MAX(id) FROM contactos),
                    TRUE
                )
            """)

    print(f"Migración completada: {len(contactos)} contactos.")


if __name__ == "__main__":
    migrar()
