"""Copia contactos locales de SQLite a la cuenta indicada en PostgreSQL."""

import argparse
import os
import sqlite3
from pathlib import Path

import psycopg

RUTA_DB = Path(__file__).with_name("contactos.db")
DATABASE_URL = os.environ.get("DATABASE_URL")


def migrar(correo_propietario):
    if not DATABASE_URL:
        raise RuntimeError("Define DATABASE_URL con la conexión de PostgreSQL destino.")
    if not RUTA_DB.exists():
        raise FileNotFoundError(f"No se encontró la base de datos local: {RUTA_DB}")

    sqlite = sqlite3.connect(RUTA_DB)
    sqlite.row_factory = sqlite3.Row
    try:
        contactos = sqlite.execute(
            "SELECT id, nombre, telefono, correo, categoria FROM contactos ORDER BY id"
        ).fetchall()
    finally:
        sqlite.close()

    if not contactos:
        print("La base SQLite no contiene contactos para migrar.")
        return

    with psycopg.connect(
        DATABASE_URL,
        connect_timeout=10,
        sslmode="require",
    ) as postgres:
        with postgres.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS usuarios (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre VARCHAR(80) NOT NULL,
                    correo VARCHAR(254) NOT NULL UNIQUE,
                    password_hash TEXT NOT NULL,
                    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS contactos (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nombre TEXT NOT NULL,
                    telefono TEXT NOT NULL,
                    correo TEXT,
                    categoria TEXT NOT NULL,
                    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE CASCADE
                )
            """)
            cursor.execute("""
                ALTER TABLE contactos
                ADD COLUMN IF NOT EXISTS usuario_id BIGINT
                REFERENCES usuarios(id) ON DELETE CASCADE
            """)
            cursor.execute(
                "SELECT id FROM usuarios WHERE LOWER(correo) = LOWER(%s)",
                (correo_propietario.strip().lower(),),
            )
            usuario = cursor.fetchone()
            if usuario is None:
                raise RuntimeError(
                    "No existe esa cuenta en PostgreSQL. Crea la cuenta en el sitio "
                    "y vuelve a ejecutar la migración con el mismo correo."
                )
            usuario_id = usuario[0]

            cursor.execute("SELECT COUNT(*) FROM contactos")
            if cursor.fetchone()[0]:
                raise RuntimeError(
                    "La tabla destino ya tiene contactos; no se migró ningún dato."
                )

            cursor.executemany(
                """INSERT INTO contactos
                   (id, nombre, telefono, correo, categoria, usuario_id)
                   VALUES (%s, %s, %s, %s, %s, %s)""",
                [
                    (
                        contacto["id"],
                        contacto["nombre"],
                        contacto["telefono"],
                        contacto["correo"],
                        contacto["categoria"],
                        usuario_id,
                    )
                    for contacto in contactos
                ],
            )
            cursor.execute("""
                SELECT setval(
                    pg_get_serial_sequence('contactos', 'id'),
                    (SELECT MAX(id) FROM contactos),
                    TRUE
                )
            """)

    print(f"Migración completada: {len(contactos)} contactos.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Copia los contactos SQLite a la cuenta indicada en PostgreSQL."
    )
    parser.add_argument(
        "--owner-email",
        required=True,
        help="Correo de una cuenta que ya existe en la base PostgreSQL destino.",
    )
    argumentos = parser.parse_args()
    migrar(argumentos.owner_email)
